#!/usr/bin/env python3
"""Budgeted modular symmetric top-class probe using conditional-leaf formula.

This independently probes the family generated by bicenter_probe.family.
Every outcome is diagnostic, not a rational-span proof or obstruction.
"""
import argparse
import hashlib
import itertools
import json
from pathlib import Path
import random
import time

import numpy as np
from flint import nmod_mat

from bicenter_probe import family
from bicenter_review_fourier import full_mod_batch


def run(n, budget, maximum_rows):
    start = time.monotonic()
    prime = 1000003
    inverse = np.zeros(prime, dtype=np.int64)
    inverse[1] = 1
    for j in range(2, prime):
        inverse[j] = prime - (prime // j) * inverse[prime % j] % prime
    keys = family(n)
    kappas = []
    for h, edges in keys:
        kappa = list(h)
        for u, v in edges:
            kappa[u] += 1
        kappas.append(kappa)
    permutations = np.array(list(itertools.permutations(range(n))), dtype=np.int64)
    print('FAMILY', n, len(keys), 'PERMUTATIONS', len(permutations), flush=True)
    rng = random.Random(241024167 + n)
    rows, frequencies, rejected = [], [], 0
    maximum_rows = maximum_rows or len(keys) + 12
    while len(rows) < maximum_rows and time.monotonic() - start < budget:
        om = [rng.randrange(1, prime) for _ in range(n - 1)]
        om.append(-sum(om) % prime)
        if not om[-1]:
            continue
        permuted = np.array(om, dtype=np.int64)[permutations]
        try:
            row = [int(full_mod_batch(k, 0, 1, 2, permuted, inverse, prime).sum() % prime)
                   for k in kappas]
        except ZeroDivisionError:
            rejected += 1
            continue
        den = 1
        for v in om:
            den = den * v % prime
        row.append((-1) ** (n - 1) * int(inverse[den]) % prime)
        rows.append(row)
        frequencies.append(om)
        if len(rows) % 10 == 0:
            print('ROWS', len(rows), 'SECONDS', round(time.monotonic() - start, 2), flush=True)
    rank = nmod_mat([row[:-1] for row in rows], prime).rank() if rows else 0
    augmented_rank = nmod_mat(rows, prime).rank() if rows else 0
    result = dict(n=n, status='MODULAR_DIAGNOSTIC_ONLY', family_orbits=len(keys),
                  rows=len(rows), rank=rank, augmented_rank=augmented_rank,
                  rejected_singular_frequencies=rejected, prime=prime,
                  frequencies=frequencies, matrix=rows,
                  producer_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  formula_sha256=hashlib.sha256(Path(__file__).with_name('bicenter_review_fourier.py').read_bytes()).hexdigest(),
                  family_sha256=hashlib.sha256(Path(__file__).with_name('bicenter_probe.py').read_bytes()).hexdigest(),
                  elapsed_seconds=time.monotonic() - start)
    destination = Path(__file__).with_name(f'bicenter_review_top_{n}.json')
    destination.write_text(json.dumps(result, indent=2) + '\n')
    print('RESULT', n, len(rows), rank, augmented_rank, 'SECONDS', result['elapsed_seconds'], flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('n', type=int)
    parser.add_argument('--seconds', type=float, default=100)
    parser.add_argument('--rows', type=int, default=0)
    args = parser.parse_args()
    run(args.n, min(args.seconds, 115), args.rows)
