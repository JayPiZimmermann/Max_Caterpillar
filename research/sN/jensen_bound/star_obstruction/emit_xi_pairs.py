#!/usr/bin/env python3
"""Emit the exact JSON-order masks; Lean independently checks coverage/validity."""
from pathlib import Path
import hashlib,json,os
ROOT=Path(__file__).resolve().parents[4]
source=ROOT/'research/sN/jensen_bound/star_obstruction/exact_tree_candidate.json'
source_bytes=source.read_bytes()
pairs=json.loads(source_bytes)['pair_order']
expected=[[s,a] for s in range(1,16) for a in range(16) if (a&s)==a]
assert pairs==expected and len(pairs)==80

def vector(xs):
 assert all(type(x) is int and 0<=x<16 for x in xs)
 return '!['+', '.join(str(x) for x in xs)+']'
text=f'''import MaxCaterpillar.Frontier.StarCertificate.XiMasks

/-! Generated by research/sN/jensen_bound/star_obstruction/emit_xi_pairs.py.
Source: exact_tree_candidate.json; SHA256 {hashlib.sha256(source_bytes).hexdigest()}.
The order is S=1,...,15, then A subset S in increasing integer-mask order.
All finite coverage claims below are kernel-checked. -/
set_option autoImplicit false
set_option maxHeartbeats 0
set_option maxRecDepth 100000
namespace MaxCaterpillar.Frontier.StarCertificate

def pairS : Fin 80 → Fin 16 := {vector([p[0] for p in pairs])}
def pairA : Fin 80 → Fin 16 := {vector([p[1] for p in pairs])}

theorem pair_valid : ∀ t : Fin 80,
    (maskSet (pairS t)).Nonempty ∧ maskSet (pairA t) ⊆ maskSet (pairS t) := by decide

theorem pair_cover : ∀ S A : Finset (Fin 4), S.Nonempty → A ⊆ S →
    ∃ t : Fin 80, maskSet (pairS t)=S ∧ maskSet (pairA t)=A := by decide

theorem pairIndex_injective : Function.Injective (fun t : Fin 80 => (pairS t,pairA t)) := by decide

#print axioms pair_valid
#print axioms pair_cover
#print axioms pairIndex_injective
end MaxCaterpillar.Frontier.StarCertificate
'''
out=ROOT/'MaxCaterpillar/Frontier/StarCertificate/XiPairs.lean';tmp=out.with_suffix('.lean.tmp')
tmp.write_text(text);os.replace(tmp,out)
print(out)
