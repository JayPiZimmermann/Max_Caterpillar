"""Emit the finite signed-subset selector schema used by the Xi bridge.

Only literal data are generated. Universal semantics live in Xi.lean and
XiStar.lean. The input tables are recomputed from permutation prefixes.
"""
from pathlib import Path
from itertools import permutations,combinations
from fractions import Fraction
import json
OUT=Path(__file__).parents[4]/'MaxCaterpillar/Frontier/StarCertificate/XiSelectors.lean'
# Resolve from this file, without assuming process working directory.
ROOT=Path(__file__).resolve().parents[4]
OUT=ROOT/'MaxCaterpillar/Frontier/StarCertificate/XiSelectors.lean'
D=Path(__file__).parent

def vec(items):return '!['+', '.join(items)+']'
def nat(n):return str(int(n))
def boolean(b):return 'true' if b else 'false'
def rat(s):
 q=Fraction(s)
 return f'({q.numerator} / {q.denominator} : ℚ)' if q.denominator!=1 else f'({q.numerator} : ℚ)'
def selected(chosen):
 leaves=sum(1<<i for i in chosen if i<4)
 return (True,15&~leaves) if 4 in chosen else (False,leaves)
def table(name,type_,rows,render):return f'def {name} : {type_} :=\n  '+vec([vec([render(x) for x in row]) for row in rows])+'\n\n'

def main():
 c=json.load(open(D/'certificate_small_candidate.json'));P=list(permutations(range(5)))
 chain=[[selected(p[:r]) for r in range(1,5)] for p in P]
 coarse=[[g[0],g[3]]+[selected((p[i],p[j])) for i,j in combinations(range(5),2) if (i,j) not in [(0,2),(2,4)]] for p,g in zip(P,chain)]
 s='''import MaxCaterpillar.Frontier.StarCertificate.Xi

/-! Generated by research/sN/jensen_bound/star_obstruction/emit_xi_selectors.py.
Finite literals only. All semantic bridges are proved in Xi and XiStar. -/
set_option autoImplicit false
set_option maxHeartbeats 0
set_option maxRecDepth 100000
namespace MaxCaterpillar.Frontier.StarCertificate
open BigOperators

'''
 s+=table('subsetForms','Fin 15 → RationalForm 4',[[int(m>>i&1) for i in range(4)] for m in range(1,16)],rat)
 s+=table('coarseForms','Fin 10 → RationalForm 4',c['H'],rat)
 s+='def starOmega : RationalForm 4 := '+vec(list(map(rat,[10,-20,20,-10])))+'\n\n'
 s+=table('permutationTable','Fin 120 → Fin 5 → Fin 5',P,nat)
 s+='def centerBeforeMask : Fin 120 → Fin 16 := '+vec([nat(sum(1<<i for i in p[:p.index(4)])) for p in P])+'\n\n'
 for prefix,data,dim in [('chain',chain,4),('coarse',coarse,10)]:
  s+=table(prefix+'Negative',f'Fin 120 → Fin {dim} → Bool',[[a for a,b in row] for row in data],boolean)
  s+=table(prefix+'Mask',f'Fin 120 → Fin {dim} → ℕ',[[b for a,b in row] for row in data],nat)
 s+='''def signDigit : Sign → ℕ
  | .neg => 0
  | .zero => 1
  | .pos => 2

def coarsePatternCode (p : Fin 10 → Sign) : ℕ :=
  ∑ j, signDigit (p j) * 3 ^ j.val

def starKappa (p : Fin 10 → Sign) : RationalForm 4 :=
  let code := coarsePatternCode p
'''
 entries=[]
 for j,p in sorted(enumerate(c['patterns']),key=lambda ip:sum((x+1)*3**i for i,x in enumerate(ip[1]))):
  code=sum((x+1)*3**i for i,x in enumerate(p));coeff=c['coefficients'][4*j:4*j+4]
  entries.append((code,vec([rat(Fraction(x)*2) for x in coeff])))
 def lookup(es,depth=1):
  pad='  '*depth
  if not es:return pad+'0'
  if len(es)==1:
   code,value=es[0];return pad+f'if code = {code} then {value} else 0'
  mid=len(es)//2;threshold=es[mid][0]
  return pad+f'if code < {threshold} then (\n'+lookup(es[:mid],depth+1)+'\n'+pad+') else (\n'+lookup(es[mid:],depth+1)+'\n'+pad+')'
 s+=lookup(entries)+'\n\n'

 s+='''def maskRef (negative : Bool) (mask : ℕ) : FormRef 15 :=
  if mask = 0 then .zero else
    if negative then .neg ⟨(mask - 1) % 15, Nat.mod_lt _ (by decide)⟩
    else .pos ⟨(mask - 1) % 15, Nat.mod_lt _ (by decide)⟩

def maskedChain (T : Fin 16) (p : Fin 120) (j : Fin 4) : FormRef 15 :=
  maskRef (chainNegative p j) (Nat.land T.val (chainMask p j))

def maskedCoarse (T : Fin 16) (p : Fin 120) (j : Fin 10) : FormRef 15 :=
  maskRef (coarseNegative p j) (Nat.land T.val (coarseMask p j))

end MaxCaterpillar.Frontier.StarCertificate
'''
 temp=OUT.with_suffix('.lean.tmp');temp.write_text(s);temp.replace(OUT)
 print(OUT,len(s))
if __name__=='__main__':main()
