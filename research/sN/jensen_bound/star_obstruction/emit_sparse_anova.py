"""Emit the fixed sparse ANOVA program; Lean checks its full finite meaning."""
from dataclasses import dataclass
from pathlib import Path
import hashlib,json

ROOT=Path(__file__).resolve().parents[4]
OUT=ROOT/'MaxCaterpillar/Frontier/StarCertificate/XiSparseProgram.lean'
INPUT=Path(__file__).with_name('exact_tree_candidate.json')

@dataclass(frozen=True)
class Entry:
    mask_t:int
    mask_p:int
    sign:int
    def render(self):
        assert 0<=self.mask_t<16 and 0<=self.mask_p<16 and self.sign in (-1,1)
        return '('+str(self.mask_t)+', '+str(self.mask_p)+', '+str(self.sign)+')'

def balanced(rows,lo=0):
    if len(rows)==1:return '['+', '.join(e.render() for e in rows[0])+']'
    split=len(rows)//2
    return '(if t.val < '+str(lo+split)+' then '+balanced(rows[:split],lo)+' else '+balanced(rows[split:],lo+split)+')'

def main():
    record=json.loads(INPUT.read_text())
    pairs=[tuple(p) for p in record['pair_order']]
    assert len(pairs)==80 and len(set(pairs))==80
    rows=[]
    for s,a in pairs:
        assert 0<s<16 and a&s==a
        row=[Entry(t,p,(-1)**((s&~t).bit_count()))
             for t in range(16) if t&~s==0
             for p in range(16) if p&s==a]
        assert len(row)==16 and len(set(row))==16
        rows.append(row)
    source='''import MaxCaterpillar.Frontier.StarCertificate.XiPairs
/-! Generated by emit_sparse_anova.py from exact_tree_candidate.json.
Source SHA256: INPUT_HASH.
The 80 nonempty-S rows have 16 entries each, hence 1280 entries in total.
The generator proposes data only; the finite semantic equalities are
checked in Lean for every row, including every parity sign. -/
set_option autoImplicit false
set_option maxHeartbeats 0
set_option maxRecDepth 100000
namespace MaxCaterpillar.Frontier.StarCertificate

abbrev AnovaEntry := Fin 16 × Fin 16 × ℤ

def anovaProgram (t : Fin 80) : List AnovaEntry :=
  PROGRAM

def canonicalAnovaEntry (S : Finset (Fin 4))
    (p : Finset (Fin 4) × Finset (Fin 4)) : AnovaEntry :=
  (setMask p.1, setMask p.2, (-1 : ℤ)^(S \\ p.1).card)

def canonicalAnovaEntries (t : Fin 80) : Finset AnovaEntry :=
  let S := maskSet (pairS t)
  let A := maskSet (pairA t)
  ((S.powerset).product
    ((Finset.univ : Finset (Fin 4)).powerset.filter (fun P => P ∩ S=A))).image
    (canonicalAnovaEntry S)

theorem anovaProgram_nodup : ∀ t : Fin 80, (anovaProgram t).Nodup := by decide

theorem anovaProgram_entries : ∀ t : Fin 80,
    (anovaProgram t).toFinset=canonicalAnovaEntries t := by decide

theorem anovaProgram_length : ∀ t : Fin 80, (anovaProgram t).length=16 := by decide

#print axioms anovaProgram_entries
end MaxCaterpillar.Frontier.StarCertificate
'''.replace('INPUT_HASH',hashlib.sha256(INPUT.read_bytes()).hexdigest()).replace('PROGRAM',balanced(rows))
    OUT.parent.mkdir(parents=True,exist_ok=True)
    tmp=OUT.with_suffix('.lean.tmp');tmp.write_text(source);tmp.replace(OUT)
    manifest={'module':str(OUT.relative_to(ROOT)),'input':str(INPUT.relative_to(ROOT)),
              'input_sha256':hashlib.sha256(INPUT.read_bytes()).hexdigest(),
              'source_sha256':hashlib.sha256(source.encode()).hexdigest(),
              'rows':[{'target':i,'S':s,'A':a,'entries':len(row)}
                      for i,((s,a),row) in enumerate(zip(pairs,rows))],
              'total_entries':sum(map(len,rows))}
    INPUT.with_name('sparse_anova_generation.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps({'path':str(OUT.relative_to(ROOT)),'rows':80,'entries':1280}))

if __name__=='__main__':main()
