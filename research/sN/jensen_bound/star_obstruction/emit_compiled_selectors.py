#!/usr/bin/env python3
"""Precompile all 16x120 selector rows; emit bounded independent Lean checks.

The row schema is typed below. The producer recomputes literal refs/bits from
permutation prefixes; Lean compares them to the canonical mask functions.
"""
from dataclasses import dataclass
from itertools import combinations,permutations
from pathlib import Path
import argparse,hashlib,os
ROOT=Path(__file__).resolve().parents[4]
BASE=ROOT/'MaxCaterpillar/Frontier/StarCertificate'
canonical=BASE/'XiSelectors.lean';CANONICAL_SHA=hashlib.sha256(canonical.read_bytes()).hexdigest()
@dataclass(frozen=True)
class Ref:
    mask:int
    negative:bool
    def __post_init__(self):assert 0<=self.mask<16
@dataclass(frozen=True)
class Row:
    chain:tuple[Ref,...]
    coarse:tuple[Ref,...]
    coefficients:tuple[tuple[int,...],...]
    def __post_init__(self):
        assert len(self.chain)==4 and len(self.coarse)==10 and len(self.coefficients)==4
        assert all(len(q)==4 and all(x in (-1,0,1) for x in q) for q in self.coefficients)

def selected(chosen,T):
    leaves=sum(1<<i for i in chosen if i<4)
    mask=(15&~leaves) if 4 in chosen else leaves
    return Ref(mask&T, bool(4 in chosen and mask&T))

def row(T,p):
    chain=tuple(selected(p[:r],T) for r in range(1,5))
    coarse=(chain[0],chain[3])+tuple(selected((p[i],p[j]),T) for i,j in combinations(range(5),2) if (i,j) not in ((0,2),(2,4)))
    coeffs=tuple(tuple((-1 if ref.negative else 1)*int(bool(ref.mask&(1<<i))) for i in range(4)) for ref in chain)
    return Row(chain,coarse,coeffs)

def vector(xs):return '!['+', '.join(xs)+']'
def integer(x):return str(x) if x>=0 else f'({x})'
def ref_literal(r):
    if r.mask==0:return '.zero'
    n=r.mask-1;assert 0<=n<15
    return f'.'+('neg' if r.negative else 'pos')+f' ⟨{n},by decide⟩'
def quad(q):return '(IntegerQuad.mk '+' '.join(map(integer,q))+')'
def row_literal(r):return '(CompiledSelectorRow.mk '+vector([ref_literal(x) for x in r.chain])+' '+vector([ref_literal(x) for x in r.coarse])+' '+vector([quad(q) for q in r.coefficients])+')'

def lookup(rows,lo=0,depth=1):
    pad='  '*depth
    if all(r==rows[0] for r in rows):return pad+row_literal(rows[0])
    k=len(rows)//2;mid=lo+k
    return pad+f'if p.val < {mid} then (\n'+lookup(rows[:k],lo,depth+1)+'\n'+pad+') else (\n'+lookup(rows[k:],mid,depth+1)+'\n'+pad+')'

def write(path,text):
    data=text.encode('utf-8')
    if path.exists() and path.read_bytes()==data:return
    path.parent.mkdir(parents=True,exist_ok=True);tmp=path.with_suffix('.lean.tmp');tmp.write_bytes(data);os.replace(tmp,path)

def data_module(T,rows):
    return f'''import MaxCaterpillar.Frontier.StarCertificate.XiCompiledSelectors.Basic
/-! Generated by emit_compiled_selectors.py. Canonical selector SHA256 {CANONICAL_SHA}.
All masks/intersections/bit coefficients are literals in each row. -/
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
namespace MaxCaterpillar.Frontier.StarCertificate.CompiledSelectorData

def row{T:02d} (p : Fin 120) : CompiledSelectorRow :=
'''+lookup(rows)+f'\n\nend MaxCaterpillar.Frontier.StarCertificate.CompiledSelectorData\n'

def check_module(T):
    chunks=[]
    for b in range(12):
        chunks.append(f'''theorem mask{T:02d}_block{b:02d}_checked :
    finAll 10 (fun j => compiledSelectorRowCheck {T} (selectorBlockPermutation {b} j)
      (CompiledSelectorData.row{T:02d} (selectorBlockPermutation {b} j)))=true := by
  with_unfolding_all rfl
''')
    combine=f'''theorem mask{T:02d}_block_checked (b : Fin 12) :
    finAll 10 (fun j => compiledSelectorRowCheck {T} (selectorBlockPermutation b j)
      (CompiledSelectorData.row{T:02d} (selectorBlockPermutation b j)))=true := by
  fin_cases b
'''+''.join(f'  · exact mask{T:02d}_block{b:02d}_checked\n' for b in range(12))
    valid=f'''
theorem mask{T:02d}_valid (p : Fin 120) : (CompiledSelectorData.row{T:02d} p).Valid {T} p := by
  obtain ⟨b,j,hp⟩ := selectorBlockPermutation_covers p
  have hc := (finAll_eq_true 10 _).mp (mask{T:02d}_block_checked b) j
  have hv := compiledSelectorRowCheck_sound {T} (selectorBlockPermutation b j) _ hc
  simpa only [hp] using hv

#print axioms mask{T:02d}_valid
'''
    return f'''import MaxCaterpillar.Frontier.StarCertificate.XiCompiledSelectors.Data.Mask{T:02d}
/-! Twelve bounded checks, each comparing only ten selector rows. -/
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 0
namespace MaxCaterpillar.Frontier.StarCertificate.CompiledSelectorChecks

'''+ '\n'.join(chunks)+'\n'+combine+valid+'\nend MaxCaterpillar.Frontier.StarCertificate.CompiledSelectorChecks\n'

def root_lookup(lo=0,hi=16,depth=1):
    pad='  '*depth
    if hi-lo==1:return pad+f'CompiledSelectorData.row{lo:02d} p'
    mid=(lo+hi)//2
    return pad+f'if T.val < {mid} then (\n'+root_lookup(lo,mid,depth+1)+'\n'+pad+') else (\n'+root_lookup(mid,hi,depth+1)+'\n'+pad+')'

def root_module():
    return ''.join(f'import MaxCaterpillar.Frontier.StarCertificate.XiCompiledSelectors.Checks.Mask{T:02d}\n' for T in range(16))+'''
/-! One balanced mask/permutation lookup supplies a whole literal selector row. -/
set_option autoImplicit false
namespace MaxCaterpillar.Frontier.StarCertificate

def compiledSelectorRow (T : Fin 16) (p : Fin 120) : CompiledSelectorRow :=
'''+root_lookup()+'''

theorem compiledSelectorRow_valid (T : Fin 16) (p : Fin 120) :
    (compiledSelectorRow T p).Valid T p := by
  fin_cases T
'''+''.join(f'  · exact CompiledSelectorChecks.mask{T:02d}_valid p\n' for T in range(16))+'''

theorem compiledSelectorRow_chain (T : Fin 16) (p : Fin 120) (j : Fin 4) :
    (compiledSelectorRow T p).chain j=maskedChain T p j :=
  (compiledSelectorRow_valid T p).1 j

theorem compiledSelectorRow_coarse (T : Fin 16) (p : Fin 120) (j : Fin 10) :
    (compiledSelectorRow T p).coarse j=maskedCoarse T p j :=
  (compiledSelectorRow_valid T p).2.1 j

theorem compiledSelectorRow_coefficients (T : Fin 16) (p : Fin 120) (j i : Fin 4) :
    ((compiledSelectorRow T p).chainCoefficients j).toForm i=
      (maskedChain T p j).integerForm starIntegerSubsetForms i :=
  (compiledSelectorRow_valid T p).2.2 j i

#print axioms compiledSelectorRow_chain
#print axioms compiledSelectorRow_coarse
#print axioms compiledSelectorRow_coefficients
end MaxCaterpillar.Frontier.StarCertificate
'''

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--mask',type=int);ap.add_argument('--all',action='store_true');args=ap.parse_args()
    masks=range(16) if args.all else [args.mask if args.mask is not None else 0]
    perms=list(permutations(range(5)));assert len(perms)==120
    for T in masks:
        assert 0<=T<16;rows=[row(T,p) for p in perms]
        write(BASE/'XiCompiledSelectors/Data'/f'Mask{T:02d}.lean',data_module(T,rows))
        write(BASE/'XiCompiledSelectors/Checks'/f'Mask{T:02d}.lean',check_module(T))
    if args.all:write(BASE/'XiCompiledSelectors.lean',root_module())
    print('emitted masks',list(masks),'rows/mask',len(perms),'proof chunk size',10)
if __name__=='__main__':main()
