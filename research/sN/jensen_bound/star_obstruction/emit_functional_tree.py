#!/usr/bin/env python3
"""Emit real-valued leaf wrappers reusing frozen checked geometry modules.

The output contains no target vanishing assumption hidden in a predicate:
all solved strata are explicit arguments to a generic exhaustive traversal.
The actual star application must prove those arguments by representative
certificates and uniform real symmetry transport.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from emit_checker_tree import (ROOT, INPUT, OUT, Lean, Solved, Impossible, Branch,
                               Chunk, Node, atomic, load, partition, terminals,
                               cleared, tree_term, SIGNS)


def emit_wrapper(chunk: Chunk, sha: str) -> Path:
    solved, _ = terminals(chunk.tree)
    base = f"Chunk{chunk.index:04d}"
    name = f"Functional{base}"
    lookup = "0"
    for leaf in reversed(solved):
        lookup = f"if p = {base}.pattern{leaf.index} then {base}.coeff{leaf.index} else ({lookup})"
    args = " ".join("(by with_unfolding_all rfl)" for _ in solved)
    patterns = "[" + ", ".join(f"{base}.pattern{leaf.index}" for leaf in solved) + "]"
    binders = "\n".join(f"    (h{leaf.index} : ∀ x, actualSigns subsetForms x = {base}.pattern{leaf.index} → ∀ t, F x t = 0)" for leaf in solved)
    cases = " | ".join(f"pattern_eq{j}" for j in range(len(solved)))
    caseproof = "\n".join(f"  · subst pattern\n    intro x hx\n    exact h{leaf.index} x (by simpa only [canonical_forms] using hx)" for leaf in solved)
    proof = (f"  rcases hp with {cases}\n{caseproof}" if solved else "  exact False.elim hp")
    text = f'''import MaxCaterpillar.Frontier.StarCertificate.Checker.Generated.{base}
import MaxCaterpillar.Frontier.StarCertificate.Checker.Functional
/-! Generated by emit_functional_tree.py; input SHA256 {sha}.
Real leaf solvers reuse every exact Farkas certificate of the numeric tree. -/
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 200000000
namespace MaxCaterpillar.Frontier.StarCertificate.Generated.{name}

def localTargets (p : Fin 15 → Sign) : Fin 80 → Fin 4 → ℤ :=
  {lookup}

theorem geometry : {base}.tree.GeometryValid starIntegerSubsetForms {base}.regionContext :=
  {base}.tree.geometry_of_valid starIntegerSubsetForms localTargets {base}.regionContext
    ({base}.valid localTargets {args})

theorem pattern_list : {base}.tree.solvedPatterns {base}.regionContext = {patterns} :=
  of_decide_eq_true (by with_unfolding_all rfl)

theorem canonical_forms : integerForms starIntegerSubsetForms = subsetForms := by
  funext j i
  exact starIntegerSubsetForms_cast j i

theorem valid (F : (Fin 4 → ℝ) → Fin 80 → ℝ)
{binders} : {base}.tree.FunctionalValid starIntegerSubsetForms F {base}.regionContext := by
  apply {base}.tree.functional_of_geometry starIntegerSubsetForms F {base}.regionContext geometry
  intro pattern hp
  rw [pattern_list] at hp
  simp only [List.mem_cons, List.not_mem_nil, or_false] at hp
{proof}

#print axioms valid
end MaxCaterpillar.Frontier.StarCertificate.Generated.{name}
'''
    path = OUT / (name + ".lean")
    atomic(path, text)
    return path


def collect_chunks(node) -> list[Chunk]:
    if isinstance(node, Chunk):
        return [node]
    if isinstance(node, Branch):
        return [c for child in node.children for c in collect_chunks(child)]
    return []


def outside(node) -> list[Impossible]:
    if isinstance(node, Chunk):
        return []
    if isinstance(node, Impossible):
        return [node]
    if isinstance(node, Solved):
        raise ValueError("Solved leaf escaped bounded partition")
    return [leaf for child in node.children for leaf in outside(child)]


def top_proof(node, context: str, count: int, indent: str = "  ") -> list[str]:
    if isinstance(node, Chunk):
        base = f"Chunk{node.index:04d}"
        result = [indent + f"have hp : ({context}) = {base}.regionContext :=",
                  indent + "  of_decide_eq_true (by with_unfolding_all rfl)",
                  indent + "rw [hp]", indent + f"apply Functional{base}.valid F"]
        for leaf in terminals(node.tree)[0]:
            result.extend([indent + f"· have hi := hLeaf ({leaf.index} : Fin {count})",
                           indent + f"  change ∀ x, actualSigns subsetForms x = {base}.pattern{leaf.index} → ∀ t, F x t = 0 at hi",
                           indent + "  exact hi"])
        return result
    if isinstance(node, Impossible):
        return [indent + f"exact (integerFarkasCheck_eq_true starIntegerSubsetForms ({context}) weights{node.index}).mp",
                indent + "  (by with_unfolding_all rfl)"]
    if isinstance(node, Solved):
        raise ValueError("Solved leaf escaped bounded partition")
    result = [indent + "refine ⟨?_, ?_, ?_⟩"]
    for sign, child in zip((-1, 0, 1), node.children):
        childctx = f"Function.update ({context}) {node.depth} (some {SIGNS[sign]})"
        lines = top_proof(child, childctx, count, indent + "  ")
        result.append(indent + "· " + lines[0][len(indent)+2:])
        result.extend(lines[1:])
    return result


def emit_half(top, sha: str) -> Path:
    if not isinstance(top, Branch) or top.depth != 0:
        raise ValueError("Expected first-form root split")
    negative, zero = top.children[:2]
    selected = collect_chunks(negative) + collect_chunks(zero)
    catalog = {leaf.index: chunk.index for chunk in selected for leaf in terminals(chunk.tree)[0]}
    count = len(catalog)
    if sorted(catalog) != list(range(count)) or count != 900:
        raise ValueError("Unexpected canonical half catalogue")
    imports = "\n".join(f"import MaxCaterpillar.Frontier.StarCertificate.Checker.Generated.FunctionalChunk{c.index:04d}" for c in selected)
    pattern_names = [f"Chunk{catalog[i]:04d}.pattern{i}" for i in range(count)]
    pattern_lookup = Lean.balanced_table(pattern_names, lambda name: name).replace("t.val", "i.val")
    lines = [f"def patterns (i : Fin {count}) : Fin 15 → Sign :=\n  {pattern_lookup}"]
    for leaf in outside(negative) + outside(zero):
        _, weights = cleared(leaf.weights)
        lines.append(f"def weights{leaf.index} : Fin 15 → ℤ := {Lean.integers(weights)}")
    for name, sign, subtree in (("negative", -1, negative), ("zero", 0, zero)):
        ctx = f"Function.update (emptyContext 15) 0 (some {SIGNS[sign]})"
        lines.extend([f"def {name}Tree : IntegerCertificateTree 15 80 :=\n  {tree_term(subtree)}",
                      f'''theorem {name}_valid (F : (Fin 4 → ℝ) → Fin 80 → ℝ)
    (hLeaf : ∀ i : Fin {count}, ∀ x, actualSigns subsetForms x = patterns i → ∀ t, F x t = 0) :
    {name}Tree.FunctionalValid starIntegerSubsetForms F ({ctx}) := by
''' + "\n".join(top_proof(subtree, ctx, count))])
    text = f'''{imports}
/-! Generated by emit_functional_tree.py; input SHA256 {sha}.
Every root-negative and root-zero branch is checked. Uniform real symmetry
and checked representative strata supply the explicit finite leaf solvers. -/
set_option autoImplicit false
set_option maxRecDepth 100000
set_option maxHeartbeats 200000000
namespace MaxCaterpillar.Frontier.StarCertificate.Generated.FunctionalHalf
''' + "\n\n".join(lines) + f'''

theorem canonical_forms : integerForms starIntegerSubsetForms = subsetForms := by
  funext j i
  exact starIntegerSubsetForms_cast j i

theorem first_form (x : Fin 4 → ℝ) : evalForm (subsetForms 0) x = x 0 := by
  simp [evalForm, subsetForms, Fin.sum_univ_succ]

theorem all_real (F : (Fin 4 → ℝ) → Fin 80 → ℝ)
    (hLeaf : ∀ i : Fin {count}, ∀ x, actualSigns subsetForms x = patterns i → ∀ t, F x t = 0)
    (heven : ∀ x t, F (-x) t = F x t) : ∀ x t, F x t = 0 :=
  functional_halfspace_even_sound starIntegerSubsetForms 0 0
    (fun x => by rw [canonical_forms, first_form]) F negativeTree zeroTree
    (negative_valid F hLeaf) (zero_valid F hLeaf) heven

#print axioms all_real
end MaxCaterpillar.Frontier.StarCertificate.Generated.FunctionalHalf
'''
    path = OUT / "FunctionalHalf.lean"
    atomic(path, text)
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=INPUT)
    parser.add_argument("--probe-index", type=int)
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()
    tree, _ = load(args.input)
    chunks, top = partition(tree, 63, 8)
    selected = collect_chunks(top.children[0]) + collect_chunks(top.children[1])
    if args.probe_index is not None:
        selected = [chunks[args.probe_index]]
    elif args.limit is not None:
        selected = selected[:args.limit]
    sha = hashlib.sha256(args.input.read_bytes()).hexdigest()
    outputs = [emit_wrapper(chunk, sha) for chunk in selected]
    if args.probe_index is None and args.limit is None:
        outputs.append(emit_half(top, sha))
    record = {"input_sha256": sha,
              "producer_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "geometry_manifest_sha256": hashlib.sha256(INPUT.with_name("checker_chunks_generation.json").read_bytes()).hexdigest(),
              "solved_faces": 900, "chunks": [c.index for c in selected],
              "outputs": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in outputs}}
    manifest = "checker_functional_probe_generation.json" if args.probe_index is not None or args.limit is not None else "checker_functional_generation.json"
    atomic(INPUT.with_name(manifest), json.dumps(record, indent=2) + "\n")
    print(json.dumps({"outputs": len(outputs), "last": str(outputs[-1].relative_to(ROOT))}))

if __name__ == "__main__":
    main()
