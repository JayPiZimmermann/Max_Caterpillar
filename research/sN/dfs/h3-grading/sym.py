"""S_N action on the dictionary and the auxiliary functions; twisted orbit sums
over Young subgroups; evaluation at random integer points.
g acts on functions by (g.f)(x) = f(x o g^{-1}); we only need that the family is
invariant and that the orbit-sum sign is the sign of the group element."""
