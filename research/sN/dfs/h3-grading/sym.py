P = 2147483647

def act_key(g, key):
    """Function x -> U_key(x permuted): coordinate i of key moved to g[i]; renormalize."""
    h, M = key
    N = len(h)
    nh = [0] * N
    for i in range(N):
        nh[g[i]] += h[i]
    nM = []
    for i, j in M:
        a, b = g[i], g[j]
        if a > b:   # relu(x_a - x_b) = relu(x_b - x_a) + x_a - x_b
            nh[a] += 1; nh[b] -= 1
            a, b = b, a
        nM.append((a, b))
    return (tuple(nh), frozenset(nM))

def act_aux(g, a):
    """Returns (aux, extra linear vector) since relu(x_b-x_a) = relu(x_a-x_b) - (x_a - x_b)."""
    if a[0] in ('pos', 'neg'):
        return (a[0], g[a[1]]), None
    i, j = g[a[1]], g[a[2]]
    if i < j:
        return ('pair', i, j), None
    return ('pair', j, i), (j, i)   # relu(x_j - x_i) with j>i: = relu(x_i-x_j) + (x_j - x_i)

def young_gens(N, mu):
    gens, s = [], 0
    for m in mu:
        for t in range(s, s + m - 1):
            g = list(range(N)); g[t], g[t + 1] = g[t + 1], g[t]
            gens.append(tuple(g))
        s += m
    return gens

def orbits(items, act, gens):
    """Orbits under the group generated by transpositions gens; each orbit as dict item->sign
    (sign of a group element mapping the representative to it), or None if the stabilizer
    contains an odd element (then sign-twisted sum vanishes)."""
    idx = {it: n for n, it in enumerate(items)}
    seen = {}
    out = []
    for it in items:
        if it in seen:
            continue
        orb = {it: 1}; stack = [it]; odd = False
        while stack:
            x = stack.pop()
            for g in gens:
                y = act(g, x)
                if y not in idx:
                    raise ValueError('family not invariant')
                s = -orb[x]
                if y in orb:
                    if orb[y] != s:
                        odd = True
                else:
                    orb[y] = s; stack.append(y)
        for y in orb:
            seen[y] = True
        out.append((orb, odd))
    return out

def eval_keys(ks, X):
    """Exact integer evaluation matrix (len(ks) x npts) of U_k at points X (npts x N)."""
    N = X.shape[1]
    pairs = [(i, j) for i in range(N) for j in range(i + 1, N)]
    pid = {p: n for n, p in enumerate(pairs)}
    H = np.array([k[0] for k in ks], dtype=np.int64)
    Mi = np.zeros((len(ks), len(pairs)), dtype=np.int64)
    for r, k in enumerate(ks):
        for p in k[1]:
            Mi[r, pid[p]] = 1
    R = np.stack([np.maximum(X[:, i] - X[:, j], 0) for i, j in pairs], axis=0)
    A = H @ X.T + Mi @ R
    return np.maximum(A, 0)

def eval_aux(auxs, X):
    rows = []
    for a in auxs:
        if a[0] == 'pos': rows.append(np.maximum(X[:, a[1]], 0))
        elif a[0] == 'neg': rows.append(np.maximum(-X[:, a[1]], 0))
        else: rows.append(np.maximum(X[:, a[1]] - X[:, a[2]], 0))
    return np.array(rows, dtype=np.int64)

def run_rank(vecs_blocks, tag):
    """vecs_blocks: list of int64 arrays (nvec_b x dim); returns ranks after each block."""
    dim = vecs_blocks[0].shape[1]
    breaks = list(np.cumsum([b.shape[0] for b in vecs_blocks]))
    fn = os.path.join('/tmp' if False else HERE, f'_tmp_{tag}.bin')
    with open(fn, 'wb') as f:
        f.write(struct.pack('<qqq', sum(b.shape[0] for b in vecs_blocks), dim, len(breaks)))
        f.write(np.array(breaks, dtype='<i8').tobytes())
        for b in vecs_blocks:
            f.write((b % P).astype('<i8').tobytes())
    out = subprocess.run([os.path.join(HERE, 'rankp'), fn], capture_output=True, text=True, check=True).stdout
    os.remove(fn)
    res = dict(tuple(map(int, l.split())) for l in out.split('\n') if l.strip())
    return [res[b] for b in breaks]
