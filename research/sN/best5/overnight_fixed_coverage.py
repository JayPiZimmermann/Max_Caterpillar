"""Independent K=2 vanishing-flat coverage audit.

Uses quadratic Boolean set functions instead of the producer's oriented
hinge coordinates. The 15 relevant values have precisely one relation:
sum_{|S|=3}v(S) = 3 sum_{|S|=4}v(S). Every coefficient in that relation
is nonzero, so every proper zero flat is specified by at most13 zeros.
All covering pairs are regenerated by forced zeros in the second neuron.
"""
import hashlib
import itertools
import json
import pickle
import time
from fractions import Fraction as Q
from pathlib import Path
import numpy as np


def rank(matrix):
    a=[[Q(x) for x in r] for r in matrix]
    r=0
    for j in range(len(a[0])):
        p=next((i for i in range(r,len(a)) if a[i][j]),None)
        if p is None: continue
        a[r],a[p]=a[p],a[r]
        z=a[r][j]; a[r]=[x/z for x in a[r]]
        for i in range(r+1,len(a)):
            z=a[i][j]
            if z:a[i]=[x-z*y for x,y in zip(a[i],a[r])]
        r+=1
    return r


def main():
    started=time.monotonic()
    rel=[frozenset(c) for n in (3,4) for c in itertools.combinations(range(5),n)]
    idx={s:i for i,s in enumerate(rel)}
    pairs=list(itertools.combinations(range(5),2))
    # Eliminate c4 using v([5])=sum c_i+sum b_ij=0.
    matrix=[[int(i in S)-int(4 in S) for i in range(4)] +
            [int(i in S and j in S)-int(4 in S) for i,j in pairs] for S in rel]
    assert rank(matrix)==14
    relation=[1 if len(S)==3 else -3 for S in rel]
    assert all(sum(c*row[j] for c,row in zip(relation,matrix))==0 for j in range(14))
    # Rank14 and a unique relation with no zero coefficient prove that
    # every14 rows are independent. Thus all masks of size<=13 occur.
    localities=[(T,o) for T in rel if len(T)==3 for o in range(5) if o not in T]
    required=[(1<<idx[T])|(1<<idx[T|{o}]) for T,o in localities]
    flatpairs=[]
    for z1 in range(1<<15):
        if z1.bit_count()>13:continue
        z2min=0
        for bits in required:
            if z1&bits!=bits:z2min|=bits
        if z2min.bit_count()>13:continue
        free=((1<<15)-1)^z2min
        subset=free
        while True:
            z2=z2min|subset
            if z1<=z2 and z2.bit_count()<=13:flatpairs.append((z1,z2))
            if not subset:break
            subset=(subset-1)&free
    aa=np.asarray(flatpairs,dtype=np.uint32)
    keys=np.full(len(aa),2**32-1,dtype=np.uint32)
    for perm in itertools.permutations(range(5)):
        bitmap=[1<<idx[frozenset(perm[i] for i in S)] for S in rel]
        lo=np.asarray([sum(bitmap[j] for j in range(8) if m>>j&1) for m in range(256)],dtype=np.uint32)
        hi=np.asarray([sum(bitmap[j+8] for j in range(7) if m>>j&1) for m in range(128)],dtype=np.uint32)
        moved=lo[aa&255]|hi[aa>>8]
        key=np.minimum(moved[:,0],moved[:,1])*32768+np.maximum(moved[:,0],moved[:,1])
        keys=np.minimum(keys,key)
    actual={(int(k)//32768,int(k)%32768) for k in keys}
    work=pickle.loads(Path("k2_work.pkl").read_bytes())
    expected={tuple(z) for z in work}
    assert len(work)==len(expected)
    assert actual==expected,(len(actual),len(expected),actual-expected,expected-actual)
    Path("overnight_fixed_coverage_pairs.json").write_text(json.dumps(sorted(actual),separators=(",",":"))+"\n")
    result={"status":"INDEPENDENT_COVERAGE_PASS","model":"all real translation-invariant pair-feature neurons",
            "rank":14,"relation":relation,"nonzero_flats":sum(1 for z in range(1<<15) if z.bit_count()<=13),
            "unordered_covering_pairs":len(flatpairs),"symmetry_orbits":len(actual),
            "work_sha256":hashlib.sha256(Path("k2_work.pkl").read_bytes()).hexdigest(),
            "checker_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "seconds":time.monotonic()-started}
    Path("overnight_fixed_coverage.json").write_text(json.dumps(result,sort_keys=True,indent=2)+"\n")
    print(json.dumps(result,sort_keys=True),flush=True)


if __name__=="__main__":main()
