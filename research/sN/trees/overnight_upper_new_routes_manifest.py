#!/usr/bin/env python3
"""Integrity and optional fresh replay of the compact new-route checkpoint.

--check is integrity only. --replay regenerates all finite chamber systems
in a temporary directory and checks their ranks, integer-row fingerprints,
and positive coefficient identities; it does not prove the uniform notes.
Use the h5-growth Python environment for --replay.
"""
from pathlib import Path
from fractions import Fraction as Q
import contextlib,hashlib,importlib,io,json,sys,tempfile,time

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
DEST=HERE/'overnight_upper_new_routes_manifest.json'


def paths():
    stems=['tropical_min','full_cycle','full_cycle_states','permutohedron','fan_lift','fan_lift_exact','path_locality']
    files=[HERE/f'overnight_upper_{s}.py' for s in stems]
    files += [HERE/f'overnight_upper_{s}.md' for s in ['tropical_min','full_cycle','permutohedron','relative_nc','koszul_filling','path_locality']]
    files += [HERE/'overnight_upper_new_routes_summary.json',Path(__file__),HERE/'overnight_upper_run.py',
              HERE/'overnight_upper_path_locality.json',HERE/'overnight_upper_tropical_min_b2.json',HERE/'overnight_upper_tropical_min_b3.json',
              HERE/'overnight_upper_fan_lift_exact_6.json',HERE/'exponential_families_probe.py',HERE/'exponential_families.py',
              HERE/'all_tree_dfs/rational_identity.py',HERE.parent/'cycles/cycle_fourier.py',
              HERE.parent/'best5/overnight_fixed_cross_net9_17.json']
    tags=['tropical_min_b2','tropical_min_b3','full_cycle_n5_b3','full_cycle_states_n5_b2',
          'full_cycle_states_n6_b1','full_cycle_states_n6_b2','permutohedron_n3_h6','permutohedron_n4_h6',
          'permutohedron_n5_h6','fan_lift_5','fan_lift_6','fan_lift_exact_6','path_locality']
    for tag in tags:
        files += [HERE/f'overnight_upper_{tag}.log',HERE/f'overnight_upper_{tag}_exit.json']
    return sorted(set(files))


def write():
    entries=[]
    for p in paths():
        b=p.read_bytes();entries.append(dict(path=str(p.relative_to(ROOT)),bytes=len(b),sha256=hashlib.sha256(b).hexdigest()))
    data=dict(status='FROZEN_COMPACT_RESEARCH_CHECKPOINT',scope='Mathematical notes plus regenerable finite research controls; not Lean verification.',
              excluded='Large raw chamber matrices are regenerated by --replay. Their producer-receipt hashes in the summary are historical provenance, not required external files.',
              files=entries,total_bytes=sum(r['bytes'] for r in entries),
              check='python3 research/sN/trees/overnight_upper_new_routes_manifest.py --check',
              replay='research/sN/dfs/h5-growth/venv/bin/python research/sN/trees/overnight_upper_new_routes_manifest.py --replay')
    DEST.write_text(json.dumps(data,indent=2)+'\n');print('WROTE',len(entries),'FILES',data['total_bytes'],'BYTES')


def check():
    data=json.loads(DEST.read_text())
    for r in data['files']:
        b=(ROOT/r['path']).read_bytes()
        assert len(b)==r['bytes'] and hashlib.sha256(b).hexdigest()==r['sha256'],r['path']
    print('INTEGRITY PASS',len(data['files']),'FILES',data['total_bytes'],'BYTES')


def replay():
    start=time.monotonic();summary=json.loads((HERE/'overnight_upper_new_routes_summary.json').read_text())
    expected={r['producer_receipt']:r for r in summary['records']}
    jobs=[('tropical_min',(2,12),'tropical_min_b2'),('tropical_min',(3,12),'tropical_min_b3'),
          ('full_cycle',(5,3),'full_cycle_n5_b3'),('full_cycle_states',(5,2),'full_cycle_states_n5_b2'),
          ('full_cycle_states',(6,1),'full_cycle_states_n6_b1'),('full_cycle_states',(6,2),'full_cycle_states_n6_b2'),
          ('permutohedron',(3,6),'permutohedron_n3_h6'),('permutohedron',(4,6),'permutohedron_n4_h6'),
          ('permutohedron',(5,6),'permutohedron_n5_h6'),('fan_lift',(6,),'fan_lift_6'),
          ('fan_lift_exact',(6,),'fan_lift_exact_6'),('path_locality',(),'path_locality')]
    with tempfile.TemporaryDirectory(prefix='max-caterpillar-new-routes-') as temp:
        for module,args,tag in jobs:
            mod=importlib.import_module('overnight_upper_'+module);mod.HERE=Path(temp)
            with contextlib.redirect_stdout(io.StringIO()):mod.main(*args)
            name='overnight_upper_'+tag+'.json';got=json.loads((Path(temp)/name).read_text())
            if name in expected:
                old=expected[name]
                for key in ('status','exact_ranks','ranks','results'):
                    if key in old:assert got[key]==old[key],(name,key)
                if 'integer_rows_sha256' in old:
                    digest=hashlib.sha256(json.dumps(got['integer_rows'],separators=(',',':')).encode()).hexdigest()
                    assert digest==old['integer_rows_sha256'],name
                if 'coefficients' in got:
                    cs=list(map(Q,got['coefficients']))
                    assert all(sum(c*x for c,x in zip(cs,row[:-1]))==row[-1] for row in got['integer_rows']),name
            if tag=='path_locality':
                old=json.loads((HERE/name).read_text())
                assert got['controls']==old['controls'] and got['results']==old['results']
            print('REPLAY PASS',tag,round(time.monotonic()-start,2),'SECONDS',flush=True)
    print('ALL FINITE REPLAYS PASS; uniform arguments remain mathematical proofs in the notes.')


if __name__=='__main__':
    if '--write' in sys.argv:write()
    else:
        check()
        if '--replay' in sys.argv:replay()
