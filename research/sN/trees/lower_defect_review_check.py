#!/usr/bin/env python3
"""Independent coverage and exact-arithmetic check of the d<=1 separator.

Uses exhaustive roots/orientations, not the producer's sink/excess-mark
parametrization. Recomputes every Fourier row from normalized integer heads
and positive-endpoint cuts, not the producer's root-away cuts. Requires no
FLINT and solves no linear system. Budget 120 seconds.
"""
import hashlib
import itertools
import json
import math
from pathlib import Path
import time

import networkx as nx
import numpy as np

HERE = Path(__file__).resolve().parent
ROWS = HERE/'lower_defect_review_exact_rows_7.json'
CERT = HERE/'lower_defect_review_separator_7.json'


def main():
    start = time.monotonic()
    data = json.loads(ROWS.read_text())
    cert = json.loads(CERT.read_text())
    assert cert['status'] == 'EXACT_FINITE_EVALUATION_SEPARATOR'
    assert cert['rows_sha256'] == hashlib.sha256(ROWS.read_bytes()).hexdigest()
    m = data['arity']; n = m-1
    units = data['representatives']
    graphs = []
    for shape in data['shapes']:
        G = nx.Graph(); G.add_nodes_from(range(1,m)); G.add_edges_from(shape['edges'])
        assert nx.is_tree(G)
        graphs.append(G)
    # Independent completeness check of the unlabeled shape list via all
    # labeled trees, generated by their Prüfer sequences.
    prufer_count = 0
    for seq in itertools.product(range(n),repeat=n-2):
        G = nx.from_prufer_sequence(seq)
        matches = [nx.is_isomorphic(G,H) for H in graphs]
        assert sum(matches) == 1
        prufer_count += 1
    raw_units = allowed_raw = 0
    for shape,G in enumerate(graphs):
        nodes = tuple(sorted(G))
        edges = tuple(sorted(tuple(sorted(e)) for e in G.edges()))
        autos = list(nx.algorithms.isomorphism.GraphMatcher(G,G).isomorphisms_iter())

        def orbit_key(kappa):
            return min(tuple(kappa[a[v]] for v in nodes) for a in autos)

        expected = set()
        for root in nodes:
            for bits in itertools.product((0,1),repeat=n-1):
                oriented = [(u,v) if b else (v,u) for (u,v),b in zip(edges,bits)]
                kappa = {v:int(v == root) for v in nodes}
                for u,v in oriented:
                    kappa[u] += 1
                raw_units += 1
                if sum(z == 0 for z in kappa.values()) <= 1:
                    expected.add(orbit_key(kappa)); allowed_raw += 1
        actual = []
        for unit in units:
            if unit['shape'] != shape:
                continue
            kappa = {v:int(v == unit['root']) for v in nodes}
            for u,v in unit['edges']:
                kappa[u] += 1
            assert sum(z == 0 for z in kappa.values()) <= 1
            actual.append(orbit_key(kappa))
        assert len(actual) == len(set(actual))
        assert set(actual) == expected
    print('COVERAGE',prufer_count,'labelled trees',raw_units,'root/orientation choices',
          allowed_raw,'allowed',len(units),'function orbits',flush=True)
    # Rebuild Fourier factors from the normalized head h=κ-outdegree_<.
    # Each cut is the component at the positive (smaller) endpoint. The
    # two factors are q+a*H and q+a*(H+1), H=sum(h on that component).
    normalized = []
    for unit in units:
        G = nx.Graph(unit['edges'])
        edges = tuple(sorted(tuple(sorted(e)) for e in G.edges()))
        kappa = {v:int(v == unit['root']) for v in G}
        for u,v in unit['edges']:
            kappa[u] += 1
        head = dict(kappa)
        for u,v in edges:
            head[u] -= 1
        head[0] = -1
        assert sum(head.values()) == 0
        factors = []
        for u,v in edges:
            H = G.copy(); H.remove_edge(u,v)
            component = set(nx.node_connected_component(H,u))
            shift = sum(head[x] for x in component)
            assert shift == int(unit['excess'] in component)-int(unit['defect'] in component)
            factors.append((sum(1<<x for x in component),shift))
        normalized.append(factors)
    needed = sorted({mask for fs in normalized for mask,shift in fs})
    perms = np.array(list(itertools.permutations(range(m))),dtype=np.int64)
    verified_rows = []
    for idx,(pt,scale_text,stored) in enumerate(zip(data['points'],data['scales'],data['integer_rows'])):
        assert time.monotonic()-start < 120
        scale = int(scale_text)
        om = np.array(pt,dtype=np.int64)[perms]
        apex = om[:,0]
        nums = ((-apex)**(m-4)).tolist()
        qs = {mask:om[:,[i for i in range(m) if mask>>i&1]].sum(axis=1)
              for mask in needed}
        bound = 2*abs(pt[0])
        common = math.lcm(*range(1,bound+1))**(2*(m-2))
        assert common%scale == 0
        divisor = common//scale
        reconstructed = []
        for fs in normalized:
            denominator = np.ones(len(perms),dtype=object)
            for mask,shift in fs:
                q = qs[mask]
                left,right = q+shift*apex,q+(shift+1)*apex
                assert np.all(left != 0) and np.all(right != 0)
                assert np.max(np.abs(left)) <= bound and np.max(np.abs(right)) <= bound
                denominator *= left*right
            raw = 0
            for num,den in zip(nums,denominator):
                quotient,remainder = divmod(common,int(den))
                assert remainder == 0
                raw += num*quotient
            value,remainder = divmod(raw,divisor)
            assert remainder == 0
            reconstructed.append(value)
        target,remainder = divmod(common,math.prod(pt))
        assert remainder == 0
        target *= (-1)**(m-1)
        target,remainder = divmod(target,divisor)
        assert remainder == 0
        reconstructed.append(target)
        assert reconstructed == list(map(int,stored))
        verified_rows.append(reconstructed)
        print('VERIFIED ROW',idx+1,'seconds',round(time.monotonic()-start,3),flush=True)
    weights = list(map(int,cert['scaled_row_weights']))
    assert len(weights) == len(verified_rows)
    for j in range(len(units)):
        assert sum(w*row[j] for w,row in zip(weights,verified_rows)) == 0
    target = sum(w*row[-1] for w,row in zip(weights,verified_rows))
    assert target == int(cert['target_value']) and target != 0
    receipt = dict(status='INDEPENDENT_EXACT_SEPARATOR_CHECK_PASS',arity=m,defect_bound=1,
                   labelled_trees=prufer_count,root_orientation_choices=raw_units,
                   allowed_root_orientation_choices=allowed_raw,orbits=len(units),
                   verified_rows=len(verified_rows),target_nonzero=True,
                   independent_mechanisms=['Pruefer shape coverage','all roots and orientations',
                     'normalized-head Fourier factors','integer separator dot products'],
                   rows_sha256=hashlib.sha256(ROWS.read_bytes()).hexdigest(),
                   certificate_sha256=hashlib.sha256(CERT.read_bytes()).hexdigest(),
                   checker_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                   elapsed_seconds=time.monotonic()-start,budget_seconds=120,
                   trust_boundary='Exact finite Fourier certificate plus mathematical formula; not Lean')
    (HERE/'lower_defect_review_check_7.json').write_text(json.dumps(receipt,indent=2)+'\n')
    print('DONE',receipt,flush=True)


if __name__ == '__main__':
    main()
