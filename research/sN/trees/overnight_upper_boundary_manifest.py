#!/usr/bin/env python3
"""Frozen interval/ordered-boundary checkpoint and bounded fresh replay.

The large head-exchange matrix is omitted: its complete semantic digest is
retained and --replay regenerates and exactly checks it in a temporary
directory. The small receipts, sources, and proof notes are self-contained.
This checks research certificates; it does not constitute Lean verification.
"""
from pathlib import Path
import hashlib, json, os, resource, subprocess, sys, tempfile, time

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DEST = HERE / 'overnight_upper_boundary_manifest.json'
JOBS = [('interval_states', (), 'interval_states', 'h5-growth'),
        ('interval_polynomial', (8,), 'interval_polynomial', 'h5-growth'),
        ('interval_local', (), 'interval_local', 'h5-growth'),
        ('ordered_lift', (), 'ordered_lift', 'h5-growth'),
        ('ordered_exchange', (), 'ordered_exchange', 'h5-growth'),
        ('ordered_product', (), 'ordered_product', 'h5-growth'),
        ('triangle_product', (), 'triangle_product', 'h4-general-neurons'),
        ('product_family', (6,), 'product_family_6', 'h5-growth'),
        ('product_symmetric', (), 'product_symmetric_6', 'h5-growth'),
        ('product_signs', (), 'product_signs_6', 'h5-growth')]


def semantic(obj):
    if isinstance(obj, dict):
        return {k: semantic(v) for k, v in obj.items()
                if k not in ('seconds', 'elapsed_seconds')}
    if isinstance(obj, list):
        return [semantic(v) for v in obj]
    return obj


def digest(obj):
    return hashlib.sha256(json.dumps(semantic(obj), sort_keys=True,
                                    separators=(',', ':')).encode()).hexdigest()


def paths():
    out = [Path(__file__), HERE / 'overnight_upper_run.py',
           HERE / 'all_tree_dfs/rational_identity.py']
    for module, _, receipt, _ in JOBS:
        out.append(HERE / ('overnight_upper_' + module + '.py'))
        if module != 'ordered_exchange':
            out.append(HERE / ('overnight_upper_' + receipt + '.json'))
        tag = module if module == 'product_signs' else receipt
        out += [HERE / ('overnight_upper_' + tag + '.log'),
                HERE / ('overnight_upper_' + tag + '_exit.json')]
    out += [HERE / ('overnight_upper_' + s + '.md') for s in
            ('interval_states', 'interval_local', 'ordered_lift',
             'ordered_product', 'product_boundary', 'relative_nc', 'koszul_filling')]
    return sorted(set(out))


def write():
    entries = []
    for path in paths():
        raw = path.read_bytes()
        entries.append(dict(path=str(path.relative_to(ROOT)), bytes=len(raw),
                            sha256=hashlib.sha256(raw).hexdigest()))
    jobs = []
    for module, args, receipt, environment in JOBS:
        record = json.loads((HERE / ('overnight_upper_' + receipt + '.json')).read_text())
        jobs.append(dict(module=module, args=args, receipt=receipt,
                         environment=environment, status=record['status'],
                         semantic_sha256=digest(record)))
    result = dict(status='FROZEN_INTERVAL_AND_BOUNDARY_RESEARCH_CHECKPOINT',
                  scope='Exact finite controls and mathematical proof notes; no uniform exponential construction and no Lean claim.',
                  excluded='The 2.4 MB ordered_exchange raw matrix is regenerated by --replay and checked against its complete semantic SHA256.',
                  files=entries, jobs=jobs, total_bytes=sum(r['bytes'] for r in entries),
                  check='python3 research/sN/trees/overnight_upper_boundary_manifest.py --check',
                  replay='python3 research/sN/trees/overnight_upper_boundary_manifest.py --replay')
    DEST.write_text(json.dumps(result, indent=2) + '\n')
    print('FROZEN', len(entries), 'FILES', result['total_bytes'], 'BYTES')


def check():
    result = json.loads(DEST.read_text())
    for record in result['files']:
        raw = (ROOT / record['path']).read_bytes()
        assert len(raw) == record['bytes'], record['path']
        assert hashlib.sha256(raw).hexdigest() == record['sha256'], record['path']
    print('INTEGRITY PASS', len(result['files']), 'FILES', result['total_bytes'], 'BYTES', flush=True)
    return result


def replay(result):
    start = time.monotonic()
    environment = os.environ.copy()
    for name in ('OPENBLAS_NUM_THREADS', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS',
                 'NUMEXPR_NUM_THREADS', 'FLINT_NUM_THREADS'):
        environment[name] = '1'

    def limits():
        resource.setrlimit(resource.RLIMIT_AS, (3 * 1024 ** 3, 3 * 1024 ** 3))
        resource.setrlimit(resource.RLIMIT_CORE, (0, 0))

    code = ('import importlib,json,sys; from pathlib import Path; '
            'sys.path.insert(0,sys.argv[1]); '
            'm=importlib.import_module("overnight_upper_"+sys.argv[2]); '
            'm.HERE=Path(sys.argv[3]); m.main(*json.loads(sys.argv[4]))')
    with tempfile.TemporaryDirectory(prefix='max-caterpillar-boundary-') as temp:
        for job in result['jobs']:
            python = ROOT / 'research/sN/dfs' / job['environment'] / 'venv/bin/python'
            command = [str(python), '-c', code, str(HERE), job['module'], temp,
                       json.dumps(job['args'])]
            completed = subprocess.run(command, env=environment, cwd=ROOT,
                                       capture_output=True, text=True, timeout=300,
                                       preexec_fn=limits)
            assert completed.returncode == 0, (job['module'], completed.stdout, completed.stderr)
            record = json.loads((Path(temp) / ('overnight_upper_' + job['receipt'] + '.json')).read_text())
            assert digest(record) == job['semantic_sha256'], job['module']
            print('REPLAY PASS', job['module'], round(time.monotonic() - start, 2), 'SECONDS', flush=True)
    print('ALL TEN EXACT/DIAGNOSTIC PRODUCERS REPLAYED; EACH RETAINS ITS STATED SCOPE.', flush=True)


if __name__ == '__main__':
    if '--write' in sys.argv:
        write()
    else:
        result = check()
        if '--replay' in sys.argv:
            replay(result)
