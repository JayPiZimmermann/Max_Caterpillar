#!/usr/bin/env python3
"""Independent finite convolution controls for one marked primitive."""
from fractions import Fraction as Q
from functools import lru_cache
from pathlib import Path
import hashlib,json,math
HERE=Path(__file__).parent

@lru_cache(None)
def compositions(total,parts):
    if parts==1:return ((total,),)
    return tuple((i,)+tail for i in range(total+1) for tail in compositions(total-i,parts-1))

def bernoulli_plus(limit):
    b=[Q(1)]
    for n in range(1,limit+1):
        b.append(-sum(Q((-1)**i,math.factorial(i+1))*b[n-i] for i in range(1,n+1)))
    return [v*math.factorial(n) for n,v in enumerate(b)]

def marked_convolution(n):
    coefficients=[Q(0)]*(n+1)
    # Split the original word p^n a among k nonempty ordered tensor slots.
    # The slot containing a may have zero p's; every other slot needs one.
    for k in range(1,n+2):
        for mark_slot in range(k):
            for remaining in compositions(n-k+1,k):
                counts=[r+int(i!=mark_slot) for i,r in enumerate(remaining)]
                multiplicity=math.factorial(n)//math.prod(math.factorial(r) for r in counts)
                position=sum(counts[:mark_slot+1])
                coefficients[position]+=Q((-1)**(k-1)*multiplicity,k)
    return coefficients

def main():
    B=bernoulli_plus(12);records=[]
    for n in range(13):
        actual=marked_convolution(n)
        expected=[B[n]*(-1)**(n-j)*math.comb(n,j) for j in range(n+1)]
        assert actual==expected
        if n:assert sum(actual)==0
        records.append(dict(ordinary_letters=n,bernoulli=str(B[n]),
                            coefficients_by_mark_position=list(map(str,actual))))
    # Unmarked convolution uses k! times Stirling numbers of the second kind.
    stirling=[[1]]
    for n in range(1,18):
        previous=stirling[-1];row=[0]*(n+1)
        for k in range(1,n+1):row[k]=(previous[k-1] if k-1<len(previous) else 0)+k*(previous[k] if k<len(previous) else 0)
        stirling.append(row)
        value=sum((-1)**(k-1)*math.factorial(k-1)*row[k] for k in range(1,n+1))
        assert value==int(n==1)
    result=dict(status='EXACT_MARKED_EULERIAN_CONVOLUTION_CONTROLS_PASSED',records=records,
        unmarked_degrees_checked=17,
        producer_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        scope='Uniform identity in the cocommutative Hopf subalgebra generated by two primitives, checked by unshuffle convolution independently of the reciprocal-series coefficients. No geometric class-map or network sufficiency claim.')
    (HERE/'overnight_upper_marked_eulerian.json').write_text(json.dumps(result,indent=2)+'\n')
    print(result['status'],'MARKED_DEGREES',len(records),'UNMARKED_DEGREES',17)

if __name__=='__main__':main()
