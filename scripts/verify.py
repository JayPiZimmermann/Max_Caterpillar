#!/usr/bin/env python3
"""Build the project, re-elaborate exact MAX claims, and audit their axioms.

Python >= 3.8, Lean/Lake from lean-toolchain. No third-party Python packages.
On the author's cluster run this script inside a reserved compute allocation.
"""
import argparse
import datetime
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]


def run(args):
    result = subprocess.run(args, cwd=ROOT, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT)
    if result.returncode:
        print(result.stdout, file=sys.stderr)
        raise SystemExit(result.returncode)
    return result.stdout


def uncomment(text):
    """Remove nested Lean comments and string literals before lexical checks."""
    result, i, depth = [], 0, 0
    while i < len(text):
        if text.startswith('/-', i):
            depth += 1
            i += 2
        elif depth and text.startswith('-/', i):
            depth -= 1
            i += 2
        elif depth:
            result.append('\n' if text[i] == '\n' else ' ')
            i += 1
        elif text.startswith('--', i):
            end = text.find('\n', i)
            i = len(text) if end < 0 else end
        elif text[i] == '"':
            i += 1
            while i < len(text):
                if text[i] == '\\':
                    i += 2
                elif text[i] == '"':
                    i += 1
                    break
                else:
                    i += 1
            result.append(' ')
        else:
            result.append(text[i])
            i += 1
    if depth:
        raise ValueError('Unclosed Lean comment')
    return ''.join(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--no-build', action='store_true',
                        help='Skip Lake build; exact statements still elaborate afresh.')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'verification/main.json').read_text())
    cpwl_sources = sorted((ROOT / 'MaxNN' / 'CPWL').rglob('*.lean'))
    forbidden_sources = cpwl_sources + [ROOT / 'MaxCaterpillar' / 'Archive.lean']
    remaining = [str(path.relative_to(ROOT)) for path in forbidden_sources if path.is_file()]
    if remaining:
        raise SystemExit('Sources outside the MAX-only scope remain:\n' + '\n'.join(remaining))
    lean_files = sorted(p for p in ROOT.rglob('*.lean')
                        if '.lake' not in p.parts and '.git' not in p.parts)
    bad = []
    for path in lean_files:
        for match in re.finditer(r'\b(sorry|admit|axiom|native_decide)\b',
                                 uncomment(path.read_text())):
            bad.append(str(path.relative_to(ROOT)) + ': ' + match.group())
    if bad:
        raise SystemExit('Forbidden proof constructs:\n' + '\n'.join(bad))

    target = ROOT / 'Verification/Statements.lean'
    target.parent.mkdir(exist_ok=True)
    lines = ['-- Generated by scripts/verify.py from verification/main.json.',
             'import MaxCaterpillar',
             'open BigOperators', 'open MaxNN MaxCaterpillar', '']
    for claim in manifest['claims']:
        lines += ['example : ' + claim['type'] + ' :=',
                  '  @' + claim['declaration'],
                  '#print axioms ' + claim['declaration'], '']
    target.write_text('\n'.join(lines))
    (ROOT / 'verification/logs').mkdir(exist_ok=True)
    if not args.no_build:
        print('Building All and Verification.Statements ...', flush=True)
        output = run(['lake', 'build', 'All', 'Verification.Statements'])
        (ROOT / 'verification/logs/build.log').write_text(output)
    print('Re-elaborating the exact statements and auditing axioms ...', flush=True)
    output = run(['lake', 'env', 'lean', 'Verification/Statements.lean'])
    (ROOT / 'verification/logs/statements.log').write_text(output)
    if re.search(r'\b(?:sorryAx|warning: declaration uses .sorry.)\b', output):
        raise SystemExit('Lean reported an incomplete proof.')
    allowed = set(manifest['allowed_axioms'])
    receipts = []
    for claim in manifest['claims']:
        name = claim['declaration']
        match = re.search("'" + re.escape(name) + r"' depends on axioms:\s*\[([^]]*)\]",
                          output, re.S)
        empty = re.search("'" + re.escape(name) + "' does not depend on any axioms", output)
        if match:
            axioms = sorted(a.strip() for a in match.group(1).split(',') if a.strip())
        elif empty:
            axioms = []
        else:
            raise SystemExit('No axiom receipt for ' + name + '\n' + output)
        if set(axioms) - allowed:
            raise SystemExit('Unexpected axioms for ' + name + ': ' + repr(axioms))
        receipts.append(dict(claim, axioms=axioms, status='VERIFIED'))
    files = sorted(set(lean_files + [target, ROOT / 'verification/main.json',
                                    ROOT / 'lean-toolchain', ROOT / 'lake-manifest.json']))
    hashes = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in files}
    digest = hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest()
    revision = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    status = subprocess.run(['git', 'status', '--porcelain', '--untracked-files=no'],
                            cwd=ROOT, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.DEVNULL)
    clean_revision = (revision.stdout.strip() if revision.returncode == 0 and
                      status.returncode == 0 and not status.stdout.strip() else None)
    certificate = {
        'checked_at_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        # A dirty-tree receipt is identified by `source_sha256` and the complete
        # `source_files` table.  Recording the preceding commit would falsely
        # attribute new sources to old history, especially before a root commit.
        'source_commit': clean_revision,
        'source_sha256': digest,
        'lean_version': run(['lake', 'env', 'lean', '--version']).strip(),
        'commands': ([] if args.no_build else [['lake', 'build', 'All', 'Verification.Statements']])
                    + [['lake', 'env', 'lean', 'Verification/Statements.lean']],
        'claims': receipts, 'source_files': hashes,
    }
    (ROOT / 'verification/certificate.json').write_text(json.dumps(certificate, indent=2) + '\n')
    print('PASS: {} exact statements; {} Lean files; only permitted axioms.'.format(
        len(receipts), len(lean_files)), flush=True)


if __name__ == '__main__':
    main()
